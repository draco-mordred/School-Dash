import mongoose, { Schema, Document } from "mongoose";

export type AttendanceStatus = "present" | "absent" | "late" | "excused" | "unverified";

export interface IAttendance extends Document {
  student?: mongoose.Types.ObjectId;
  lecturer?: mongoose.Types.ObjectId;
  course?: mongoose.Types.ObjectId;
  subject?: mongoose.Types.ObjectId | null;
  class: mongoose.Types.ObjectId;
  academicYear: mongoose.Types.ObjectId;
  date: Date;
  dayOfWeek: "Monday" | "Tuesday" | "Wednesday" | "Thursday" | "Friday";
  status: AttendanceStatus;
  notes?: string;
  absenceReason?: string;
  autoGenerated?: boolean;
  submissionSource?: "tap" | "offline-retry" | "system";
  session?: mongoose.Types.ObjectId | null;
  proximity?: {
    studentLat?: number | null;
    studentLng?: number | null;
    distanceMeters?: number | null;
    verificationStatus?: "pending" | "verified" | "out-of-range" | "lecturer-absent" | "unverified";
    capturedAt?: Date | null;
  };
  escalatedToAdmin?: boolean;
  approvedBy?: mongoose.Types.ObjectId; // For excused absences, who approved it (e.g., admin or teacher)
  lecturerApproval?: "approved" | "not-approved" | null;
  lecturerApprovalDate?: Date | null;
  hodApproval?: "approved" | "not-approved" | null;
  hodApprovalDate?: Date | null;
} 

const AttendanceSchema = new Schema(
  {
    student: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    lecturer: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    course: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Course",
      required: true,
    },
    subject: {
      type: mongoose.Schema.Types.ObjectId,
      default: null,
    },
    class: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Class",
      required: true,
    },
    academicYear: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AcademicYear",
      required: true,
    },
    date: {
      type: Date,
      required: true,
      default: Date.now,
    },
    dayOfWeek: {
      type: String,
      enum: ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"],
      required: true,
    },
    status: {
      type: String,
      enum: ["present", "absent", "late", "excused", "unverified"],
      required: true,
      default: "present",
    },
    notes: {
      type: String,
      default: "",
    },
    absenceReason: {
      type: String,
      default: "",
      trim: true,
    },
    autoGenerated: {
      type: Boolean,
      default: false,
    },
    submissionSource: {
      type: String,
      enum: ["tap", "offline-retry", "system"],
      default: "system",
    },
    session: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "LectureSession",
      default: null,
    },
    proximity: {
      studentLat: { type: Number, default: null },
      studentLng: { type: Number, default: null },
      distanceMeters: { type: Number, default: null },
      verificationStatus: {
        type: String,
        enum: ["pending", "verified", "out-of-range", "lecturer-absent", "unverified"],
        default: "pending",
      },
      capturedAt: { type: Date, default: null },
    },
    escalatedToAdmin: {
      type: Boolean,
      default: false,
    },
    approvedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    lecturerApproval: {
      type: String,
      enum: ["approved", "not-approved", null],
      default: null,
    },
    lecturerApprovalDate: {
      type: Date,
      default: null,
    },
    hodApproval: {
      type: String,
      enum: ["approved", "not-approved", null],
      default: null,
    },
    hodApprovalDate: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
  }
);

export default mongoose.model<IAttendance>("Attendance", AttendanceSchema);
