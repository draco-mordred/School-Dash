// Phase B — Auto Lecture Attendance scheduler.
//
// 1. planLectureSessionsForDay(): runs on a short cron (see
//    lectureAttendancePlanner in inngest/functions.ts). Each run materializes
//    one LectureSession per non-clinical timetable period for TODAY —
//    effectively the "00:00 timer" from the design, but restart-safe: missed
//    runs catch up, timetable edits mid-day are picked up, and the unique
//    (class, course, subject, lecturer, date) index makes repeats harmless.
//    Weekends are skipped for lectures (clinical postings run separately).
//
// 2. runLectureAttendanceTick(): runs every 5 minutes.
//    - pre-lecture reminders (>= 1 hour before start) to class students
//      and the lecturer, once per session;
//    - opens sessions whose 75%-of-duration trigger has arrived:
//      generates the per-student attendance list (shared LATIFAH core),
//      links records to the session (autoGenerated, status "unverified"
//      until the student taps — Phase C), and notifies students within
//      the 5-minute cadence to tap Present or Absent;
//    - closes sessions at lecture end + 5 minutes grace (D2).
//
// NOTE: period times are interpreted in the server's local timezone.
// Deployment environments should set TZ=Africa/Lagos (or equivalent).

const DAY_MAP: Record<number, string> = {
  0: "Sunday",
  1: "Monday",
  2: "Tuesday",
  3: "Wednesday",
  4: "Thursday",
  5: "Friday",
  6: "Saturday",
};

const HH_MM = /^([01]?\d|2[0-3]):([0-5]\d)$/;
const HOUR_MS = 60 * 60 * 1000;
const MINUTE_MS = 60 * 1000;
const OPEN_GRACE_AFTER_CLOSE = 2 * HOUR_MS; // open catch-up limit
const IS_OBJECT_ID = (v: unknown) =>
  typeof v === "string" && /^[a-fA-F0-9]{24}$/.test(v);

// Pure window math (D1/D2/D8): trigger at 75% of lecture duration,
// close at lecture end + 5 minutes, reminder 60 minutes before start.
export const computeLectureWindow = (
  startTime: string,
  endTime: string,
  dayDate: Date,
) => {
  if (!HH_MM.test(startTime ?? "") || !HH_MM.test(endTime ?? "")) return null;
  const [sh, sm] = startTime.split(":").map(Number);
  const [eh, em] = endTime.split(":").map(Number);
  const base = new Date(dayDate);
  base.setHours(0, 0, 0, 0);
  const lectureStart = new Date(base);
  lectureStart.setHours(sh, sm, 0, 0);
  const lectureEnd = new Date(base);
  lectureEnd.setHours(eh, em, 0, 0);
  if (lectureEnd.getTime() <= lectureStart.getTime()) return null; // overnight lectures unsupported
  const durationMs = lectureEnd.getTime() - lectureStart.getTime();
  const triggerAt = new Date(
    lectureStart.getTime() + Math.round(durationMs * 0.75),
  );
  const closesAt = new Date(lectureEnd.getTime() + 5 * MINUTE_MS);
  const reminderAt = new Date(lectureStart.getTime() - HOUR_MS);
  return { lectureStart, lectureEnd, triggerAt, closesAt, reminderAt };
};

// Timetable periods reference "subject" which may be either a top-level
// Course id or (legacy) an embedded subject id stored against ref "Course".
// Resolves to the (course, embedded subject) pair the LATIFAH generation
// core expects, preferring the embedded subject whose lecturer matches the
// period's lecturer.
const resolvePeriodSubject = async (
  subjectRef: unknown,
  lecturerId: string | null,
  classCourseIds: unknown[],
): Promise<{
  courseId: string;
  subjectId: string;
} | null> => {
  const sid =
    typeof subjectRef === "object" && subjectRef !== null
      ? String((subjectRef as any)._id ?? "")
      : String(subjectRef ?? "");
  if (!IS_OBJECT_ID(sid)) return null;

  const course = await Course.findById(sid).lean<any>();
  if (course) {
    const subjects = (course.subjects ?? []) as any[];
    if (!subjects.length) return null; // generation core needs embedded subjects
    const match =
      subjects.find(
        (s: any) =>
          lecturerId &&
          Array.isArray(s.lecturer) &&
          s.lecturer.some((l: any) => String(l?._id ?? l) === lecturerId),
      ) ?? subjects[0];
    return { courseId: String(course._id), subjectId: String(match._id) };
  }

  // Legacy: sid is an embedded subject id — search the class's courses.
  for (const ref of classCourseIds ?? []) {
    const cid = String((ref as any)?._id ?? ref ?? "");
    if (!IS_OBJECT_ID(cid)) continue;
    const c = await Course.findById(cid).lean<any>();
    if (!c) continue;
    const match = (c.subjects ?? []).find(
      (s: any) =>
        String(s._id) === sid ||
        String(s.subjectID) === sid ||
        String(s.subjectUID ?? "") === sid,
    );
    if (match) return { courseId: String(c._id), subjectId: String(match._id) };
  }
  return null;
};

const EMPTY_SNAPSHOT = {
  name: "",
  room: "",
  lat: 0,
  lng: 0,
  radiusMeters: 150,
};

export const planLectureSessionsForDay = async (dayDate = new Date()) => {
  const dayName = DAY_MAP[dayDate.getDay()];
  if (!dayName || dayName === "Saturday" || dayName === "Sunday") {
    return { dayName: dayName ?? "unknown", weekend: true, created: 0, skippedPeriods: 0, errors: [] as string[] };
  }
  const now = new Date();
  let created = 0;
  let skippedPeriods = 0;
  const errors: string[] = [];

  const timetables = await Timetable.find({}).lean<any[]>();
  // Phase G2 pilot gate: when AUTO_ATTENDANCE_PILOT_CLASSES is set to a
  // comma-separated list of class ids, only those classes get planned
  // auto sessions; unset = every class (current behaviour). Lets the
  // pilot run on one class without touching the rest of the school.
  const pilotEnv = String(process.env.AUTO_ATTENDANCE_PILOT_CLASSES ?? "").trim();
  const pilotClasses = new Set(
    pilotEnv ? pilotEnv.split(",").map((s) => s.trim()).filter(Boolean) : [],
  );
  for (const timetable of timetables) {
    if (pilotClasses.size > 0 && !pilotClasses.has(String(timetable.class))) continue;
    try {
      const clock = await AcademicClock.findOne({
        class: timetable.class,
        academicYear: timetable.academicYear,
      }).lean<any>();
      const activePhase = clock ? resolveAcademicClockPhase(clock) : null;
      const phaseConfig = (activePhase?.phase ?? null) as Record<string, any> | null;
      const phaseId = activePhase?.phaseId ?? null;
      const state = getTimetableForPhase(
        timetable,
        phaseId,
        phaseConfig?.timetablePhaseId ?? null,
      );
      if (!state.configured) continue;

      const daySchedule = (state.schedule ?? []).find(
        (d: any) => (d.day ?? "").toLowerCase() === dayName.toLowerCase(),
      );
      if (!daySchedule?.periods?.length) continue;

      const classDoc = await Class.findById(timetable.class)
        .select("name courses")
        .lean<any>();
      if (!classDoc) continue;

      for (const period of daySchedule.periods as any[]) {
        if (!period?.subject || period.isClinical || period.isOptional) continue;
        const window = computeLectureWindow(
          period.startTime,
          period.endTime,
          dayDate,
        );
        if (!window) {
          skippedPeriods += 1;
          continue;
        }
        if (window.closesAt.getTime() <= now.getTime()) continue; // already over
        const lecturerId = period.lecturer ? String(period.lecturer) : null;
        const resolved = await resolvePeriodSubject(
          period.subject,
          lecturerId,
          classDoc.courses ?? [],
        );
        if (!resolved) {
          skippedPeriods += 1;
          continue;
        }

        let venueId: any = null;
        let venueSnapshot = { ...EMPTY_SNAPSHOT };
        const venueRef = String(period.venue ?? "");
        if (IS_OBJECT_ID(venueRef)) {
          const venue = await Venue.findById(venueRef).lean<any>();
          if (venue && venue.isActive !== false) {
            venueId = venue._id;
            venueSnapshot = {
              name: venue.name ?? "",
              room: venue.room ?? "",
              lat: venue.lat ?? 0,
              lng: venue.lng ?? 0,
              radiusMeters: venue.radiusMeters ?? 150,
            };
          }
        }

        try {
          await LectureSession.create({
            class: timetable.class,
            course: resolved.courseId,
            subject: resolved.subjectId,
            lecturer: lecturerId,
            academicYear: timetable.academicYear,
            date: dayDate,
            dayOfWeek: dayName,
            source: "lecture",
            autoGenerated: true,
            venue: venueId,
            venueSnapshot,
            window: {
              lectureStart: window.lectureStart,
              lectureEnd: window.lectureEnd,
              triggerAt: window.triggerAt,
              openedAt: null,
              closesAt: window.closesAt,
            },
            lecturerCheckIn: { lat: null, lng: null, at: null, verified: false },
            notifications: { preLectureSentAt: null, openedNoticeSentAt: null },
            status: "generated",
            escalation: { escalatedToAdmin: false, escalatedAt: null },
            createdBy: null,
          });
          created += 1;
        } catch (err: any) {
          if (err?.code === 11000 || /duplicate key/i.test(String(err?.message ?? ""))) {
            continue; // already planned for today
          }
          skippedPeriods += 1;
          errors.push("session create failed: " + String(err?.message ?? err));
        }
      }
    } catch (err: any) {
      errors.push("timetable " + String(timetable._id) + ": " + String(err?.message ?? err));
    }
  }

  return { dayName, weekend: false, created, skippedPeriods, errors };
};

