const describeSession = async (session: any) => {
  const classDoc = await Class.findById(session.class)
    .select("name students")
    .populate("students", "_id")
    .lean<any>();
  const course = await Course.findById(session.course).lean<any>();
  let subjectLabel = "Lecture";
  if (course) {
    const subject = (course.subjects ?? []).find(
      (s: any) => String(s._id) === String(session.subject),
    );
    subjectLabel = subject?.name ?? course.name ?? subjectLabel;
  }
  const timeLabel = session.window?.lectureStart
    ? new Date(session.window.lectureStart).toLocaleTimeString("en-US", {
        hour: "numeric",
        minute: "2-digit",
      })
    : "";
  const venueLabel = session.venueSnapshot?.name
    ? session.venueSnapshot.name + (session.venueSnapshot.room ? " · " + session.venueSnapshot.room : "")
    : "";
  const closesLabel = session.window?.closesAt
    ? new Date(session.window.closesAt).toLocaleTimeString("en-US", {
        hour: "numeric",
        minute: "2-digit",
      })
    : "";
  return { classDoc, subjectLabel, timeLabel, venueLabel, closesLabel };
};

const notifySessionError = (scope: string, err: unknown) =>
  console.warn("[lecture-scheduler] " + scope + " failed:", err);

const sendPreLectureReminder = async (session: any) => {
  const { classDoc, subjectLabel, timeLabel, venueLabel } =
    await describeSession(session);
  if (!classDoc) return false;
  const where = venueLabel ? " in " + venueLabel : "";
  const meta = {
    sessionId: String(session._id),
    classId: String(session.class),
    courseId: String(session.course),
    subjectId: String(session.subject ?? ""),
  };
  for (const student of classDoc.students ?? []) {
    const uid = String((student as any)?._id ?? student ?? "");
    if (!IS_OBJECT_ID(uid)) continue;
    try {
      await createNotificationIfUnique({
        userId: new mongoose.Types.ObjectId(uid),
        role: "student",
        title: "Upcoming lecture reminder",
        message: subjectLabel + " for " + classDoc.name + " starts at " + timeLabel + where + ".",
        type: "timetable",
        link: "/timetable",
        metadata: meta,
      });
    } catch (err) {
      notifySessionError("reminder for student " + uid, err);
    }
  }
  if (session.lecturer && IS_OBJECT_ID(String(session.lecturer))) {
    try {
      await createNotificationIfUnique({
        userId: new mongoose.Types.ObjectId(String(session.lecturer)),
        role: "teacher",
        title: "Lecture reminder",
        message: "You are scheduled to take " + subjectLabel + " for " + classDoc.name + " at " + timeLabel + where + ".",
        type: "timetable",
        link: "/timetable",
        metadata: meta,
      });
    } catch (err) {
      notifySessionError("reminder for lecturer " + String(session.lecturer), err);
    }
  }
  return true;
};

const openLectureSession = async (session: any, now: Date) => {
  // Generate the per-student attendance list via the shared LATIFAH core
  // (one weekend guard, one duplicate guard, one lecturer notification).
  // DUPLICATE_SESSION means a manual session already generated records for
  // this class/course/subject/date — proceed and just link them.
  try {
    await generateSessionRecords({
      courseId: String(session.course),
      classId: String(session.class),
      academicYearId: String(session.academicYear),
      date: new Date(session.date).toISOString(),
      subjectId: String(session.subject),
      requesterId: session.lecturer ? String(session.lecturer) : undefined,
    });
  } catch (err) {
    if (
      !(err instanceof AttendanceGenerationError) ||
      err.code !== "DUPLICATE_SESSION"
    ) {
      throw err;
    }
  }

  // Link today's records to this session. Records start "unverified"
  // (displayed as pending everywhere) until the student taps Present/Absent
  // in Phase C; taps then overwrite status and capture proximity data.
  const startOfDay = new Date(session.date);
  startOfDay.setHours(0, 0, 0, 0);
  const endOfDay = new Date(startOfDay);
  endOfDay.setDate(endOfDay.getDate() + 1);
  await Attendance.updateMany(
    {
      class: session.class,
      course: session.course,
      subject: session.subject,
      date: { $gte: startOfDay, $lt: endOfDay },
    },
    { $set: { session: session._id, autoGenerated: true, status: "unverified" } },
  );

  // "Tap now" notice — the 5-minute tick cadence guarantees students are
  // notified within 5 minutes of the 75% trigger.
  const { classDoc, subjectLabel, closesLabel, venueLabel } =
    await describeSession(session);
  if (classDoc) {
    const meta = {
      sessionId: String(session._id),
      classId: String(session.class),
      courseId: String(session.course),
      subjectId: String(session.subject ?? ""),
    };
    for (const student of classDoc.students ?? []) {
      const uid = String((student as any)?._id ?? student ?? "");
      if (!IS_OBJECT_ID(uid)) continue;
      try {
        await createNotificationIfUnique({
          userId: new mongoose.Types.ObjectId(uid),
          role: "student",
          title: "Attendance check-in is open",
          message: "Tap Present or Absent now for " + subjectLabel + " in " + classDoc.name + ". The window closes at " + closesLabel + (venueLabel ? " (location: " + venueLabel + ")" : "") + ".",
          type: "attendance",
          link: "/attendance",
          metadata: meta,
        });
      } catch (err) {
        notifySessionError("open notice for student " + uid, err);
      }
    }
  }

  await LectureSession.updateOne(
    { _id: session._id },
    {
      $set: {
        status: "open",
        "window.openedAt": now,
        "notifications.openedNoticeSentAt": now,
      },
    },
  );
};

// Phase J4 (D15): day-close finality for clinical complaints. Open
// complaints on completed clinical sessions become final at 19:00 of the
// session day — the recorded attendance stands and the student is told.
export const runClinicalComplaintFinalizer = async (now = new Date()) => {
  const lookbackStart = new Date(now);
  lookbackStart.setDate(lookbackStart.getDate() - 2);
  lookbackStart.setHours(0, 0, 0, 0);
  const sessions = await ClinicalAttendance.find({
    status: "completed",
    date: { $gte: lookbackStart, $lte: now },
    "attendees.complaint.status": "open",
  }).lean<any[]>();

  let finalized = 0;
  let notified = 0;
  for (const session of sessions) {
    const sessionClose = new Date(new Date(session.date).getTime());
    sessionClose.setHours(19, 0, 0, 0);
    if (now.getTime() < sessionClose.getTime()) continue; // day not closed yet

    for (const attendee of session.attendees ?? []) {
      const complaint = (attendee as any).complaint;
      if (!complaint || complaint.status !== "open") continue;
      await ClinicalAttendance.updateOne(
        {
          _id: session._id,
          "attendees._id": (attendee as any)._id,
          "attendees.complaint.status": "open",
        },
        {
          $set: {
            "attendees.$.complaint.status": "dismissed",
            "attendees.$.complaint.resolution": "Not resolved by day-close — the recorded attendance is final",
            "attendees.$.complaint.resolvedAt": now,
          },
        },
      );
      finalized += 1;
      const uid = String((attendee as any).student?._id ?? (attendee as any).student);
      if (IS_OBJECT_ID(uid)) {
        try {
          await createNotificationIfUnique({
            userId: new mongoose.Types.ObjectId(uid),
            role: "student",
            title: "Clinical complaint closed",
            message: "Your complaint for " + String(session.title) + " was not resolved by day-close. The recorded attendance stands as final.",
            type: "attendance",
            metadata: { clinicalSessionId: String(session._id) },
          });
          notified += 1;
        } catch (err) {
          notifySessionError("clinical complaint finalizer for student " + uid, err);
        }
      }
    }
  }
  return { finalized, notified };
};

export const runLectureAttendanceTick = async (now = new Date()) => {
  // 1. Pre-lecture reminders: once per session, when start is within an hour
  //    (or already past). Skip sessions whose window is already over.
  const remindersDue = await LectureSession.find({
    status: { $in: ["generated", "open"] },
    "notifications.preLectureSentAt": null,
    "window.lectureStart": { $ne: null, $lte: new Date(now.getTime() + HOUR_MS) },
  }).lean<any[]>();
  let remindersSent = 0;
  for (const session of remindersDue) {
    const closesAt = session.window?.closesAt ? new Date(session.window.closesAt) : null;
    if (closesAt && closesAt.getTime() <= now.getTime()) continue; // too late
    try {
      const sent = await sendPreLectureReminder(session);
      await LectureSession.updateOne(
        { _id: session._id, "notifications.preLectureSentAt": null },
        { $set: { "notifications.preLectureSentAt": now } },
      );
      if (sent) remindersSent += 1;
    } catch (err) {
      notifySessionError("reminder for session " + String(session._id), err);
    }
  }

  // 2. Open sessions at the 75% trigger. If the server was down past the
  //    close time + grace, close them out instead of opening stale windows.
  const toOpen = await LectureSession.find({
    status: "generated",
    "window.triggerAt": { $ne: null, $lte: now },
  }).lean<any[]>();
  let opened = 0;
  let staleClosed = 0;
  const openErrors: string[] = [];
  for (const session of toOpen) {
    const closesAt = session.window?.closesAt ? new Date(session.window.closesAt) : null;
    if (closesAt && closesAt.getTime() + OPEN_GRACE_AFTER_CLOSE <= now.getTime()) {
      await LectureSession.updateOne(
        { _id: session._id, status: "generated" },
        { $set: { status: "closed" } },
      );
      staleClosed += 1;
      continue;
    }
    try {
      await openLectureSession(session, now);
      opened += 1;
    } catch (err: any) {
      openErrors.push("session " + String(session._id) + ": " + String(err?.message ?? err));
    }
  }

  // 3. Close open sessions at lecture end + 5 minutes grace.
  const closeRes = await LectureSession.updateMany(
    { status: "open", "window.closesAt": { $ne: null, $lte: now } },
    { $set: { status: "closed" } },
  );

  // 4. Re-verify provisional proximity records (e.g. the lecturer checked in
  // after students tapped, or records left pending at tap time).
  const reverified = await processPendingVerifications(now);

  // 5. Phase H3: nudge clinical supervisors to create their attendance
  //    session (15 min before the scheduled timetable end, then every
  //    30 min, capped 4h after the end). Runs on weekends too (D10).
  const clinicalNudges = await runClinicalSessionNudges(now);

  // 6. Phase J4 (D15): finalize open clinical complaints at day-close.
  const clinicalFinalized = await runClinicalComplaintFinalizer(now);

  return {
    remindersSent,
    opened,
    staleClosed,
    closed: closeRes.modifiedCount ?? 0,
    proximityReverified: reverified.processed,
    clinicalNudges: clinicalNudges.nudged.length,
    clinicalComplaintsFinalized: clinicalFinalized.finalized,
    openErrors,
  };
};

// Phase D3 — 18:00 SLA sweeper (server timezone; set TZ=Africa/Lagos).
// Absent taps without a reason become final absent (auto), lecturers get a
// per-session summary notification, and provisional proximity records get a
// final verification pass. Remaining "unverified" records stay flagged for
// the lecturer's Phase E complaint-driven queue.
export const runAttendanceSlaSweeper = async (now = new Date()) => {
  const startOfDay = new Date(now);
  startOfDay.setHours(0, 0, 0, 0);
  const endOfDay = new Date(startOfDay);
  endOfDay.setDate(endOfDay.getDate() + 1);
  const sessions = await LectureSession.find({
    source: "lecture",
    date: { $gte: startOfDay, $lt: endOfDay },
  }).lean<any[]>();

  let finalizedAbsent = 0;
  let lecturerNotifications = 0;
  const errors: string[] = [];

  for (const session of sessions) {
    try {
      const records = await Attendance.find({ session: session._id }).lean<any[]>();
      let absentFinalized = 0;
      for (const record of records) {
        if (record.status === "absent" && !record.absenceReason) {
          await Attendance.updateOne(
            { _id: record._id },
            {
              $set: {
                absenceReason: "No reason provided (auto-finalized at 18:00)",
              },
            },
          );
          absentFinalized += 1;
        }
      }
      finalizedAbsent += absentFinalized;

      // Final verification pass for anything still provisional/pending.
      await processSessionVerifications(session, now);

      const unverifiedCount = records.filter(
        (r: any) => r.status === "unverified",
      ).length;

      if (
        session.lecturer &&
        IS_OBJECT_ID(String(session.lecturer)) &&
        (absentFinalized > 0 || unverifiedCount > 0)
      ) {
        await createNotificationIfUnique({
          userId: new mongoose.Types.ObjectId(String(session.lecturer)),
          role: "teacher",
          title: "Attendance SLA summary",
          message:
            absentFinalized +
            " absence(s) finalized (no reason provided). " +
            unverifiedCount +
            " record(s) still need your verification.",
          type: "attendance",
          link: "/attendance",
          metadata: { sessionId: String(session._id) },
        });
        lecturerNotifications += 1;
      }
    } catch (err: any) {
      errors.push("session " + String(session._id) + ": " + String(err?.message ?? err));
    }
  }

  return {
    sessions: sessions.length,
    finalizedAbsent,
    lecturerNotifications,
    errors,
  };
};
